import pandas as pd
from pydeseq2.ds import DeseqDataSet

# 1. Apply the actual sum >= 10 filter from cell 0ArpdhMcxVIX
gene_filter = cleaned_counts.sum(axis=0) >= 10
filtered_counts_actual = filtered_counts.loc[:, gene_filter]

# 2. Re-build metadata correctly by mapping each sample to its group
control = ["GSM3684385", "GSM3684386", "GSM3684387", "GSM3684391", "GSM3684392", "GSM3684393"]
treatment = ["GSM3684388", "GSM3684389", "GSM3684394", "GSM3684395", "GSM3684396"]

cond_map = {}
for sample in filtered_counts_actual.index:
    if sample in control:
        cond_map[sample] = "control"
    elif sample in treatment:
        cond_map[sample] = "treatment"
    else:
        cond_map[sample] = "unknown"

metadata_fixed = pd.DataFrame({"condition": cond_map})

# 3. Initialize and run PyDESeq2 with the corrected data
dds = DeseqDataSet(
    counts=filtered_counts_actual,
    metadata=metadata_fixed,
    design_factors="condition",
    n_cpus=4,
)

dds.deseq2()

from pydeseq2.default_inference import DefaultInference
from pydeseq2.ds import DeseqStats

inference = DefaultInference()

# Corrected DeseqStats import and corrected contrast labels to match metadata ("treatment" vs "control")
stats_res = DeseqStats(
    dds,
    contrast=["condition", "treatment", "control"],
    inference=inference
)

stats_res.summary()

results_df = stats_res.results_df.copy()

results_df.head()

import mygene


mg = mygene.MyGeneInfo()

raw_genes_ids = results_df.index.tolist()

clean_ids = [str(gid).split(".")[0] for gid in raw_genes_ids]

query_results = mg.querymany(
    clean_ids,
    scopes=["ensembl.gene", "entrezgene","symbol"],
    fields = ["symbol","name"],
    species = "human",
    as_dataframe=True,
    verbose=True,
)

from pandas.core.api import notna
mapping_dict = {}

for q_id, row in query_results.iterrows():
  if pd.notna(row["symbol"]):
    mapping_dict[q_id] = row["symbol"]
  elif pd.notna(row["name"]):
    mapping_dict[q_id] = row["name"]

results_df["Clean_ID"] = clean_ids

results_df["Symbol"] = results_df["Clean_ID"].map(mapping_dict)

results_df["Symbol"] = results_df["Symbol"].fillna(results_df.index.to_series())

results_df = results_df[["Symbol","baseMean","log2FoldChange","pvalue","padj"]]

results_df.head()

import seaborn as sns


clean_res = results_df.dropna(subset=["padj","log2FoldChange"].copy())


clean_res["-log10(padj)"] = -np.log10(clean_res["padj"])

clean_res.head()

p_value = clean_res["padj"]

lfc = clean_res["log2FoldChange"]


clean_res["Status"] = "Not Significant"

clean_res.loc[(p_value < 0.05) & (lfc > 1.00), "Status"] = "Upregulated"

clean_res.loc[(p_value < 0.05) & (lfc < -1.00), "Status"] = "Downregulated"

clean_res["Status"].value_counts()

sig_degs = clean_res[clean_res["Status"] != "Not Significant"].sort_values("padj")
sig_degs.to_csv("GSE150368_significant_degs.csv")

# 5. Print a clear summary statement
num_up = sum(clean_res["Status"] == "Upregulated")
num_down = sum(clean_res["Status"] == "Downregulated")
print(f"Discovered {len(sig_degs)} Significant DEGs ({num_up} Up, {num_down} Down)")

plt.figure (figsize = (9, 6))

colors = {"Upregulated": "green", "Downregulated": "red", "Not Significant": "grey"}
sns.scatterplot(
    data = clean_res,
    x = "log2FoldChange",
    y = "-log10(padj)",
    hue = "Status",
    palette = colors)

