raw_counts = pd.read_excel('gene_counts.xlsx')

raw_counts.columns

raw_counts.head()

if raw_counts.shape[0] > raw_counts.shape [1]:
  counts = raw_counts.T
else:
  counts = raw_counts

counts.head()

counts  = counts.round().astype(int)

new_counts = counts[counts >= 10]

new_counts.head()

# 1. Properly set GeneID as index and transpose
cleaned_counts = raw_counts.set_index('GeneID').T
cleaned_counts = cleaned_counts.round().astype(int)

# 2. Filter out low-count genes
gene_filter = cleaned_counts.sum(axis=0) >= 10
filtered_counts = cleaned_counts.loc[:, gene_filter]

# 3. Create metadata (e.g., splitting samples as normal vs tumor for demo)
# Since GSM IDs don't contain 'r_T' or 'Pca', we split them by index position or define them explicitly.
sample_names = filtered_counts.index.tolist()
# For example, let's designate the first 10 samples as 'normal' and the rest as 'tumor'
conditions = ["normal" if i < 10 else "tumor" for i in range(len(sample_names))]

metadata = pd.DataFrame(
    {"condition": conditions},
    index=filtered_counts.index
)

print("Metadata sample distribution:")
print(metadata["condition"].value_counts())

# 4. Instantiate DeseqDataSet
from pydeseq2.dds import DeseqDataSet

dds = DeseqDataSet(
    counts=filtered_counts,
    metadata=metadata,
    design_factors="condition",
    refit_cooks=True,
    n_cpus=4,
)
print("DeseqDataSet successfully created!")

dds.deseq2()

from pydeseq2.default_inference import DefaultInference

inference = DefaultInference(n_cpus = 2)

# Fix the contrast column and levels to match the lowercase 'condition', 'tumor', and 'normal' in the metadata
stat_res = DeseqStats(
    dds,
    contrast=["condition", "tumor", "normal"],
    inference=inference
)

# Display the results summary
stat_res.summary()

results_df = stat_res.results_df.copy()
results_df.head()

