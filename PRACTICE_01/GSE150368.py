import mygene

mg = mygene.MyGeneInfo()

raw_gene_ids = results_df.index.tolist()

clean_ids = [str(gid).split(".")[0] for gid in raw_gene_ids]

query_results = mg.querymany(
    clean_ids,
    scopes=["ensembl.gene", "entrezgene", "symbol"],
    fields=["symbol", "name"],
    species="human",
    as_dataframe=True
)

# Build a mapping dictionary {Gene_ID: Common_Symbol}
mapping_dict = {}
for q_id, row in query_results.iterrows():
    if pd.notna(row.get("symbol")):
        mapping_dict[q_id] = row["symbol"]

# Add the 'Symbol' column to your results dataframe
results_df["Clean_ID"] = clean_ids
results_df["Symbol"] = results_df["Clean_ID"].map(mapping_dict)

# Fallback: keep original ID if no common symbol is found (e.g., long non-coding RNAs)
results_df["Symbol"] = results_df["Symbol"].fillna(results_df.index.to_series())

# Reorder columns
results_df = results_df[["Symbol", "baseMean", "log2FoldChange", "pvalue", "padj"]]
results_df.head(5)

import seaborn as sns

clean_res = results_df.dropna(subset=["padj", "log2FoldChange"]).copy()

clean_res["-log10(padj)"] = -np.log10(clean_res["padj"])

p_value = clean_res["padj"]
lfc = clean_res["log2FoldChange"]

# Initialize 'Status' column as 'Not Significant'
clean_res["Status"] = "Not Significant"

# Use .loc with proper parentheses for bitwise operations
clean_res.loc[(p_value < 0.05) & (lfc > 1.00), "Status"] = "Upregulated"
clean_res.loc[(p_value < 0.05) & (lfc < -1.00), "Status"] = "Downregulated"

print(clean_res["Status"].value_counts())

sig_degs = clean_res[clean_res["Status"] != "Not Significant"].sort_values("padj")
sig_degs.to_csv("GSE150368_significant_degs.csv")

# 5. Print a clear summary statement
num_up = sum(clean_res["Status"] == "Upregulated")
num_down = sum(clean_res["Status"] == "Downregulated")
print(f"Discovered {len(sig_degs)} Significant DEGs ({num_up} Up, {num_down} Down)")

plt.figure (figsize = (9, 6))

colors = {"Upregulated": "green", "Downregulated": "red", "Not Significant": "grey"}
